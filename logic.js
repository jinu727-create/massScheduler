const DEFAULT_WEIGHTS = { count: 100, sameSlot: 30, prevWeek: 20, sameWeek: 15, prevMonth: 10 };

const pad = n => String(n).padStart(2, '0');
const ymd = (y, m, d) => `${y}-${pad(m)}-${pad(d)}`;
const ymKey = (y, m) => `${y}-${pad(m)}`;
function parseDate(s) { const [y, m, d] = s.split('-').map(Number); return new Date(Date.UTC(y, m - 1, d)); }
function fmtDate(dt) { return ymd(dt.getUTCFullYear(), dt.getUTCMonth() + 1, dt.getUTCDate()); }
function dowOf(s) { return parseDate(s).getUTCDay(); }
function addDays(s, n) { const d = parseDate(s); d.setUTCDate(d.getUTCDate() + n); return fmtDate(d); }
function daysInMonth(y, m) { return new Date(Date.UTC(y, m, 0)).getUTCDate(); }
function prevYm(y, m) { return m === 1 ? [y - 1, 12] : [y, m - 1]; }
function nextYm(y, m) { return m === 12 ? [y + 1, 1] : [y, m + 1]; }
/* 토요일 저녁 + 일요일을 한 주말로 묶기 위해, 각 날짜를 '그 주를 마치는 일요일'로 묶음 */
function weekKey(s) { const w = dowOf(s); return w === 0 ? s : addDays(s, 7 - w); }
function slotFromTime(time) {
  if (time < '08:00') return 'WEEKDAY_0600';
  if (time < '15:00') return 'WEEKDAY_1000';
  return 'WEEKDAY_1930';
}
function timeLabel(time) {
  const [h, mi] = time.split(':').map(Number);
  const ap = h < 12 ? '오전' : '오후';
  const hh = h % 12 === 0 ? 12 : h % 12;
  return `${ap} ${hh}시${mi ? ` ${mi}분` : ''}`;
}
function makeId() { return Math.random().toString(36).slice(2, 10) + Date.now().toString(36).slice(-4); }
function positionsOf(mass) {
  const p = [{ field: 'commentatorId', role: 'COMMENTATOR', label: '해설' }, { field: 'reader1Id', role: 'READER', label: '제1독서' }];
  if (mass.type === 'WEEKEND') p.push({ field: 'reader2Id', role: 'READER', label: '제2독서' });
  return p;
}
function sortMasses(arr) { return arr.sort((a, b) => (a.date + a.time).localeCompare(b.date + b.time)); }

/* 월별 미사 자동생성. mode: 'add' = 없는 것만 추가, 'regen' = 전체 새로 만듦 */
function generateMonth(y, m, templates, existing, mode) {
  const out = mode === 'regen' ? [] : existing.map(x => ({ ...x }));
  const have = new Set(out.map(x => x.date + ' ' + x.time));
  let added = 0;
  for (let d = 1; d <= daysInMonth(y, m); d++) {
    const date = ymd(y, m, d); const w = dowOf(date);
    for (const t of templates.filter(t => Number(t.dow) === w)) {
      if (have.has(date + ' ' + t.time)) continue;
      out.push({ id: makeId(), date, time: t.time, name: t.name, type: t.type, slot: t.type === 'WEEKEND' ? 'WEEKEND' : t.slot,
        commentatorId: null, reader1Id: null, reader2Id: null, locked: false, autoGenerated: true });
      have.add(date + ' ' + t.time); added++;
    }
  }
  return { masses: sortMasses(out), added };
}

function mulberry32(a) { return function () { a |= 0; a = a + 0x6D2B79F5 | 0; let t = Math.imul(a ^ a >>> 15, 1 | a); t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t; return ((t ^ t >>> 14) >>> 0) / 4294967296; }; }

function activeMembers(members) { return members.filter(m => !m.deleted && m.active !== false); }
function considered(members) { return activeMembers(members).filter(m => (m.roles || []).length && (m.availability || []).length); }

/* 배정 실행: 여러 번 시도해 가장 고른 결과 채택 */
function assignMonth({ masses, members, prevMasses = [], weights = DEFAULT_WEIGHTS, mode = "fill", trials = 50, seed, order = "chrono" }) {
  const act = activeMembers(members);
  const byId = Object.fromEntries(act.map(m => [m.id, m]));
  const partnerOf = {};
  for (const m of act) { const s = m.spouseId && byId[m.spouseId]; partnerOf[m.id] = s && s.spouseId === m.id ? s : null; }
  const couples = [];
  for (const m of act) { const p = partnerOf[m.id]; if (p && m.id < p.id) couples.push([m, p]); }
  const cons = considered(members);
  const prevCount = {}; for (const m of act) prevCount[m.id] = 0;
  for (const ms of prevMasses) for (const p of positionsOf(ms)) { const id = ms[p.field]; if (id in prevCount) prevCount[id]++; }
  const prevAvg = cons.length ? cons.reduce((s, m) => s + prevCount[m.id], 0) / cons.length : 0;
  const ctx = { act, byId, partnerOf, couples, cons, prevCount, prevAvg, w: { ...DEFAULT_WEIGHTS, ...weights }, mode, order };
  const rng = mulberry32(seed ?? Math.floor(Math.random() * 1e9));
  let best = null;
  for (let i = 0; i < trials; i++) {
    const r = runTrial(masses, ctx, rng);
    const ev = evaluate(r, ctx);
    if (!best || ev.score < best.ev.score) best = { masses: r, ev };
  }
  return { masses: best.masses, stats: best.ev };
}

function isAbsent(m, date) { return (m.absences || []).includes(date); }

function runTrial(base, ctx, rng) {
  const masses = base.map(m => ({ ...m }));
  if (ctx.mode === 'all') for (const ms of masses) if (!ms.locked) { ms.commentatorId = null; ms.reader1Id = null; ms.reader2Id = null; }
  const st = { count: {}, slot: {}, weekSlot: {}, day: {}, week: {} };
  for (const m of ctx.act) { st.count[m.id] = 0; st.slot[m.id] = {}; st.weekSlot[m.id] = {}; st.day[m.id] = new Set(); st.week[m.id] = new Set(); }
  const record = (id, ms) => {
    if (!(id in st.count)) return;
    st.count[id]++; st.day[id].add(ms.date); const wk = weekKey(ms.date); st.week[id].add(wk);
    if (ms.type === 'WEEKEND') { const k = dowOf(ms.date) + '@' + ms.time; st.slot[id][k] = (st.slot[id][k] || 0) + 1; (st.weekSlot[id][wk] ||= []).push(k); }
  };
  for (const ms of masses) for (const p of positionsOf(ms)) if (ms[p.field]) record(ms[p.field], ms);

  const eligible = (m, ms, role) => (m.roles || []).includes(role) && (m.availability || []).includes(ms.slot) && !isAbsent(m, ms.date) && !st.day[m.id].has(ms.date);
  const score = (m, ms) => {
    const w = ctx.w; let s = w.count * st.count[m.id];
    const wk = weekKey(ms.date);
    if (ms.type === 'WEEKEND') {
      const k = dowOf(ms.date) + '@' + ms.time;
      s += w.sameSlot * (st.slot[m.id][k] || 0);
      if ((st.weekSlot[m.id][addDays(wk, -7)] || []).includes(k)) s += w.prevWeek;
    }
    if (st.week[m.id].has(wk)) s += w.sameWeek;
    s += w.prevMonth * (ctx.prevCount[m.id] - ctx.prevAvg);
    return s + rng() * 5;
  };

  const weekend = masses.filter(m => m.type === 'WEEKEND');
  const weekday = masses.filter(m => m.type !== 'WEEKEND');
  const scarcity = ms => ctx.act.filter(m => (m.availability || []).includes(ms.slot) && !isAbsent(m, ms.date)).length;
  const sc = new Map(weekday.map(ms => [ms, scarcity(ms)]));
  weekday.sort((a, b) => sc.get(a) - sc.get(b) || (a.date + a.time).localeCompare(b.date + b.time));

  const order = ctx.order === "chrono" ? sortMasses([...masses]) : [...weekend, ...weekday];
  for (const ms of order) {
    if (ms.locked) continue;
    let open = positionsOf(ms).filter(p => !ms[p.field]);
    while (open.length) {
      const cache = new Map(); const S = m => { if (!cache.has(m.id)) cache.set(m.id, score(m, ms)); return cache.get(m.id); };
      let best = null;
      for (const p of open) for (const m of ctx.act) {
        if (ctx.partnerOf[m.id] || !eligible(m, ms, p.role)) continue;
        const v = S(m); if (!best || v < best.v) best = { v, set: [[p, m]] };
      }
      for (let i = 0; i < open.length; i++) for (let j = i + 1; j < open.length; j++) {
        const [pi, pj] = [open[i], open[j]];
        for (const [a, b] of ctx.couples) for (const [x, y] of [[a, b], [b, a]]) {
          if (!eligible(x, ms, pi.role) || !eligible(y, ms, pj.role)) continue;
          const v = (S(x) + S(y)) / 2; if (!best || v < best.v) best = { v, set: [[pi, x], [pj, y]] };
        }
      }
      if (!best) break;
      for (const [p, m] of best.set) { ms[p.field] = m.id; record(m.id, ms); }
      open = open.filter(p => !ms[p.field]);
    }
  }
  return masses;
}

function evaluate(masses, ctx) {
  const per = {}; for (const m of ctx.act) per[m.id] = { id: m.id, weekday: 0, weekend: 0, total: 0, slots: {} };
  const unfilled = [];
  for (const ms of masses) for (const p of positionsOf(ms)) {
    const id = ms[p.field];
    if (!id) { unfilled.push({ date: ms.date, time: ms.time, name: ms.name, label: p.label, massId: ms.id }); continue; }
    const r = per[id]; if (!r) continue;
    r.total++; if (ms.type === 'WEEKEND') { r.weekend++; const k = dowOf(ms.date) + '@' + ms.time; r.slots[k] = (r.slots[k] || 0) + 1; } else r.weekday++;
  }
  const totals = ctx.cons.map(m => per[m.id].total);
  const mean = totals.length ? totals.reduce((a, b) => a + b, 0) / totals.length : 0;
  const std = totals.length ? Math.sqrt(totals.reduce((s, x) => s + (x - mean) ** 2, 0) / totals.length) : 0;
  let repeats = 0; for (const r of Object.values(per)) for (const n of Object.values(r.slots)) repeats += Math.max(0, n - 1);
  return { per, unfilled, mean, std, repeats, min: totals.length ? Math.min(...totals) : 0, max: totals.length ? Math.max(...totals) : 0,
    score: unfilled.length * 1000 + std * 20 + repeats * 2 };
}

/* 캘린더 표기: "오전 7시 해설(류연희), 독서(이승호, 홍채원)" */
function massLine(ms, nameOf) {
  const n = id => id ? nameOf(id) : '미배정';
  const rd = ms.type === 'WEEKEND' ? `${n(ms.reader1Id)}, ${n(ms.reader2Id)}` : n(ms.reader1Id);
  return `${timeLabel(ms.time)} 해설(${n(ms.commentatorId)}), 독서(${rd})`;
}

